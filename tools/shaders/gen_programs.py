"""Generate psmhost/libScePsm/graphics/embedded_programs.inc from the program table that
ags_info.py prints (reflection.txt, section "EmbeddedShader programs"): for every
EmbeddedShader, its vertex/pixel shader names, each stage's __GLOBAL_CB__ size and the
uniform list in libScePsm's index order (PS members, then VS members; sub_1F82A0).

usage: python -I gen_programs.py <reflection.txt> <out.inc>
"""
import re, sys

lines = open(sys.argv[1], encoding="utf-8").read().splitlines()
start = next(i for i, l in enumerate(lines) if l.startswith("EmbeddedShader programs"))
progs = []
for l in lines[start + 1:]:
    m = re.match(r"\s*(\d+) (\w+)\s+vs=\s*(\d+) (\w+)\s+ps=\s*(\d+) (\w+)", l)
    if m:
        progs.append({"type": int(m[1]), "name": m[2], "vs": m[4], "ps": m[6], "u": [], "ps_size": 0, "vs_size": 0})
        continue
    m = re.match(r"\s*stage CB0 sizes: PS=(\d+), VS=(\d+)", l)
    if m and progs:
        progs[-1]["ps_size"], progs[-1]["vs_size"] = int(m[1]), int(m[2])
        continue
    m = re.match(r"\s*\[\d+\] (\S+)\s+(PS|VS) CB0 \+(\d+)\s+(\d+) bytes", l)
    if m and progs:
        progs[-1]["u"].append((m[1], 2 if m[2] == "PS" else 1, int(m[3]), int(m[4])))
out = ["// Generated by tools/shaders/gen_programs.py from the reflection of libScePsm's",
       "// embedded shaders (FW 4.03). Do not edit.",
       "// {EmbeddedShader, vs, ps, ps CB0 size, vs CB0 size, {name, stage (2 PS / 1 VS), offset, size}...}"]
for p in progs:
    us = ", ".join('{"%s", %d, %d, %d}' % u for u in p["u"])
    out.append('{%d, "%s", "%s", %d, %d, {%s}},  // %s' % (p["type"], p["vs"], p["ps"], p["ps_size"], p["vs_size"], us, p["name"]))
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out) + "\n")
print(len(progs), "programs")
