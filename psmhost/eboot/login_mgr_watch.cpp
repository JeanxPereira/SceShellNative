template <class T>
T rd(const uint8_t* p, size_t off) {
  T v;
  std::memcpy(&v, p + off, sizeof v);
  return v;
}

// SceLoginMgrEventFlag bits (event_thread.cpp Run, 0x1C87B0).
constexpr uint64_t kEvStartEventWatch = 0x20;
constexpr uint64_t kEvWatchThreadReady = 0x800;

// HOST VALUE: sceSystemStateMgrGetCurrentState (ze0ky5Q1yE8) as the watch thread reads it
// (0x215460 -> watch +76, copied to each device +268): 1000, the working state (500 is
// "main on standby"). The host runs the shell only in the working state.
constexpr int32_t kSystemStateWorking = 1000;

// The DeviceQueueMgr record (0x1CC040 / 0x1C9A30 view, 176 bytes on the console): the
// fields the login path writes and PostEvent reads.
struct Record {
  uint64_t device_id = 0;         // +8
  int32_t bus = 0;                // +20
  int32_t type = 0;               // +24
  int64_t type2 = 0;              // +32 (vtable +528)
  uint64_t functions = 0;         // +40 (0x1D4620)
  uint64_t device_unique_id = 0;  // +56 (device +216 = record +208, the BT address)
  bool is_bus_change = false;     // +64 (RunBusTransitionNewDevice)
  bool need_bond_update = false;  // +120
  bool need_ngvr_update = false;  // +121
  bool preferred = false;         // +168
};

struct LoginMgr {
  std::mutex mode_mu;                 // +20544
  int32_t mode = -1;                  // +20552 (constructor 0x1F1240: -1)
  bool watch_started = false;         // +20536
  std::mutex flag_mu;                 // SceLoginMgrEventFlag (attr 274)
  std::condition_variable flag_cv;
  uint64_t flag = 0;
  bool event_thread = false;
  bool watch_enabled = false;         // event thread object +368
  std::mutex queue_mu;                // DeviceQueueMgr
  std::deque<Record> wait_data;       // disabled-wait data (0x1CC340 / 0x1CC4E0)
  std::mutex delegate_mu;             // +20600
  int32_t (*launch_by_uri)(const char*) = nullptr;  // +21432
};

LoginMgr& mgr() {
  static LoginMgr m;
  return m;
}

int32_t current_mode() {
  std::lock_guard<std::mutex> l(mgr().mode_mu);
  return mgr().mode;
}

// The eboot's "#LOGIN MGR# " trace lines (printf format, one line).
#define lm_log(...) (std::fprintf(stderr, "#LOGIN MGR# "), std::fprintf(stderr, __VA_ARGS__), std::fputc('\n', stderr))

void set_flag(uint64_t bits) {
  {
    std::lock_guard<std::mutex> l(mgr().flag_mu);
    mgr().flag |= bits;
  }
  mgr().flag_cv.notify_all();
}

// 0x1F0950: the managed LaunchByUriAsync delegate under +20600; none -> 0x80B6000F.
int32_t invoke_launch_by_uri(const std::string& uri) {
  std::lock_guard<std::mutex> l(mgr().delegate_mu);
  if (!mgr().launch_by_uri) return static_cast<int32_t>(0x80B6000Fu);
  return mgr().launch_by_uri(uri.c_str());
}

// sce::Json value text as Ncel8t2Rrpc (Value::serialize) writes it into the URI.
std::string json_text(bool b) { return b ? "true" : "false"; }
std::string json_text(uint64_t v) { return std::to_string(v); }
std::string json_text(int64_t v) { return std::to_string(v); }

// PostEvent (0x1C9A30) for a controller record of the "login" kind.
void post_event(const Record& r) {
  // IDU / Morpheus queue deletions (sub_1EF700, type2 12) do not apply: the host is not an
  // IDU unit (SYSTEM_SPECIFIC_idu_mode reads 0) and holds no VR device.
  {
    std::lock_guard<std::mutex> l(mgr().queue_mu);
    if (!mgr().watch_enabled) {  // +368 == 0 and record +120 == 0
      lm_log("EventWatch is disabled.");
      mgr().wait_data.push_back(r);  // 0x1CC340
      return;
    }
  }
  // Record flags (+76 bits, +104, +96, +80/+81, +100, +123) are 0 for a plain controller:
  // entry "login". Members, in sce::Json::Object (strcmp-ordered map) order:
  std::map<std::string, std::string> o;
  o["entry"] = "login";
  o["deviceId"] = json_text(r.device_id);                                // _0lLK8_kDqmE (uint64)
  o["deviceUniqueId"] = json_text(static_cast<int64_t>(r.device_unique_id));  // x4AUdbhpRB0 (int64)
  o["isBusChange"] = json_text(r.is_bus_change);                         // UeuWT_yNdCQ (bool)
  o["needBondUpdate"] = json_text(r.need_bond_update);
  if (r.preferred) o["isPreferredDevice"] = "true";
  o["needNextGenVrControllerUpdate"] = json_text(r.need_ngvr_update);
  host::note_unimplemented("eboot LoginMgr PostEvent: sub_1FD100 / sub_20D7F0 (device state check before deviceUniqueId) not reproduced");
  // URI: "psaccounts:" + entry + "?" + key=value pairs joined with '&' (every member but
  // "entry", in the object's order).
  std::string uri = "psaccounts:" + o["entry"] + "?";
  bool first = true;
  for (const auto& [k, v] : o) {
    if (k == "entry") continue;
    if (!first) uri += "&";
    first = false;
    uri += k + "=" + v;
  }
  lm_log("uri=%s", uri.c_str());
  const int32_t res = invoke_launch_by_uri(uri);
  if (res < 0) lm_log("LaunchByUriAsync : %d(0x%08x)", res, static_cast<uint32_t>(res));
}

// DeviceQueueMgr::Enqueue (0x1CC040).
void enqueue(const Record& r) {
  lm_log("[DeviceQueueMgr::Enqueue]");
  post_event(r);
}

// 0x20F8E0: IsShowIncombatiblePeripheralMessage (record +228 VID / +230 PID; record +8/+12
// bus/type).
bool incompatible_peripheral(const uint8_t* rec) {
  if (rd<int32_t>(rec, 8) == 4 && rd<int32_t>(rec, 12) == 1) {
    const int32_t n = rd<int32_t>(rec, 20);
    for (int32_t i = 0; i < n && i <= 9; ++i)
      if (rd<int32_t>(rec, 24 + 16 * i) == 2) return false;
  }
  const uint16_t vid = rd<uint16_t>(rec, 228), pid = rd<uint16_t>(rec, 230);
  switch (vid) {
    case 4794: return pid == 32;
    case 5141: return (pid & 0xFC00) == 0x2000 || pid == 3;
    case 1133: return (pid & 0xFFFE) == 0xCAC0;
    case 1356:
      return (pid >= 341 && pid <= 343) || pid == 459 || pid == 616 || pid == 746 || pid == 1071 || pid == 1202 ||
             pid == 1252 || pid == 1491 || pid == 1690 || pid == 1691 || pid == 2976;
    default: return false;
  }
}

// device_manager.cpp onDeviceAdded (0x1CFD40) for a device object built from `rec` (the
// object holds the 256-byte client record at +8, so object +16 bus = record +8, +20 type =
// record +12, +208 owner = record +200, +216 = record +208; +264..+279 are the watch
// thread's state at the event, 0x219980: +268 system state, +272 the LoginMgr mode).
void on_device_added(const uint8_t* rec, bool generated) {
  const uint64_t device_id = rd<uint64_t>(rec, 0);
  const int32_t bus = rd<int32_t>(rec, 8), type = rd<int32_t>(rec, 12), owner = rd<int32_t>(rec, 200);
  const int32_t mode = current_mode();
  // Bluetooth devices: limitNumberOfBluetoothConnection (vtable +632, 0x1D7720). The host
  // pad is on USB.
  if (static_cast<uint32_t>(mode) >= 3) {
    lm_log("[onDeviceAdded] Invalid processing mode :%d", mode);
    return;
  }
  // +24 (record +16) removed: 0 in the server's records (0x75500); +268 system state is
  // kSystemStateWorking (500 -> 0x1D5510, other values -> "system state not working").
  if (mode == 2) {
    lm_log("[onDeviceAdded] not ready");
    return;
  }
  host::note_unimplemented("eboot LoginMgr onDeviceAdded: PSM event 262 OnDeviceConnected (device JSON, 0x1CFD40 -> 0x215BD0) not posted");
  if (!generated)
    host::note_unimplemented("eboot LoginMgr NotifyOnDeviceAdded (0x1EE920 -> 0x1EE940 managed DeviceBasicEvent delegate) not reproduced");
  // 0x1E02E0: bond-update bus transition — no controller update is in progress on the host.
  if (bus == 2 && type == 1) {
    lm_log("[onDeviceAdded] deviceType HDMI AUDIO.");
    return;
  }
  if (incompatible_peripheral(rec)) {
    host::note_unimplemented("eboot LoginMgr incompatible peripheral (sceMbusDisconnectDevice + notification 16) not reproduced");
    lm_log("[onDeviceAdded] IsShowIncombatiblePeripheralMessage.");
    return;
  }
  if (static_cast<uint32_t>(owner + 1) >= 2 && owner != 255) {
    lm_log("[onDeviceAdded] Assigned device userId:0x%08x.", static_cast<uint32_t>(owner));
    return;
  }
  if (type == 0) {
    host::note_unimplemented("eboot LoginMgr DualShock 3 disconnect (0x1CFD40) not reproduced");
    lm_log("[onDeviceAdded] dualshock3.");
    return;
  }
  // onDeviceAddedForEachDevice (vtable +248, 0x1DBB40) returns 0 after 0x1E7940
  // ("notifyDeviceDetected", sub_358500(2, 1)) and 0x1D51F0 for non-remote-play buses.
  host::note_unimplemented("eboot LoginMgr onDeviceAddedForEachDevice side effects (0x1E7940 sub_358500(2,1), 0x1D51F0) not reproduced");
  if (owner == 255) {
    lm_log("[onDeviceAdded] userId system.");
    return;
  }
  // plK52OfeEIc() == -1 -> CecOneTouchPlay (0x20DA70, sceSystemStateMgrSendCecOneTouchPlayCommand
  // for controller types): the host has no HDMI-CEC.
  host::note_unimplemented("eboot LoginMgr CecOneTouchPlay (0x20DA70) on device added: no HDMI-CEC on the host");
  if (device_function_bits(rec, false) == 0) {  // 0x1D4620
    lm_log("[onDeviceAdded] deviceFunction unknown.");
    return;
  }
  // tryAutoAssignManufactureMode (0x1D5720): watch +72 is 0 (not a manufacturing unit).
  // IsNeedBondUpdate (0x1DE540, type 22 on USB/BT): HOST VALUE — the host pad has no
  // controller firmware, so no controller update is needed (v50 = 0); 0x1DED50 -> "".
  // tryAutoAssignIduMode (0x1D58F0): not an IDU unit. Share Play (bus 5): no.
  // assignRemotePlay (vtable +520, 0x1D7130): 0. Bond updating (0x1DEF10): no.
  Record r;
  r.device_id = device_id;
  r.bus = bus;
  r.type = type;
  r.type2 = 22 - (bus == 0 ? 1 : 0);  // vtable +528 (0x1E76A0) for the DualSense class
  r.functions = device_function_bits(rec, false);
  r.device_unique_id = rd<uint64_t>(rec, 208);
  // EnableDeviceConnect (vtable +40, 0x1DB6F0): getControllerNum (0x1DB7F0) <= 4 on the
  // host bus (one device); 0x1E0AA0 finds no bond-update rebind entry -> connect allowed.
  // RunBusTransitionNewDevice (0x1CC1E0): no bus-transition entry for the device (0x1FDD60
  // -> 0x80B60031) -> isBusChange false.
  // USB-audio pad check (functions 1/2/9/18) and product name (function 16, 1356/2994): no.
  if (mode == 0) {
    host::note_unimplemented("eboot LoginMgr onDeviceAdded initial-setup mode (0x1E7720, PSM event 11) not reproduced");
    return;
  }
  // TryDualShockUsbConnectionChange (0x1D4790): returns 0 for a USB device (a5 && bus == 0).
  // Kiosk test nQ5AHlyJghQ: retail unit -> autoAssignComplete 0 before deviceAutoAssign.
  // deviceAutoAssign (0x1D5B80): logged-in non-guest users counted (sceUserServiceGet
  // LoginUserIdList / _7XgCmEwKrs).
  int32_t ids[users::kMaxLogin];
  users::login_user_ids(ids);
  int32_t logged = 0;
  for (int32_t id : ids) logged += id != users::kUserIdInvalid;
  bool assigned = false;
  if (logged == 0) {
    // vtable +168 (0x1DD160) returns 1 -> not assigned.
    assigned = false;
  } else {
    host::note_unimplemented("eboot LoginMgr deviceAutoAssign with logged-in users (0x1D5B80: 0x20AF60 / 0x1D5F50 / 0x1D61B0 / vtable +560) not reproduced; device left for the login screen");
  }
  // LABEL_144: controller state for an unassigned pad (vtable +24 -> 0x1D7BD0(+288),
  // 0x101010000000000): the host pad has no light bar / player LEDs.
  host::note_unimplemented("eboot LoginMgr controller state (vtable +24 -> 0x1D7BD0) for the unassigned pad not reproduced");
  lm_log("Event OnControllerActivated ");
  lm_log("isAutoAssignComplete:%d, m_systemState:%d, isSendEvent:%d", assigned ? 1 : 0, kSystemStateWorking, 1);
  if (!assigned) {
    host::note_unimplemented("eboot LoginMgr R013D1VIETQ() before the device queue (onDeviceAdded) not traced");
    enqueue(r);
  }
  // IsNeedControllerLightCalibration (0x1EF230): type2 21 is not one of 0/3/16/17.
}

// The watch thread's dispatch of one event (0x215D90 -> device lookup 0x1CE820 -> 0x1CF9B0).
void handle_event(const mbus::Event& ev, bool generated) {
  uint8_t cond[256];
  mbus::init_condition(cond, sizeof cond);
  std::memcpy(cond, &ev.device_id, 8);
  uint8_t rec[mbus::kRecordSize];
  int32_t total = 0, gen = 0;
  const bool found = mbus::get_device_info_by_condition(cond, 0, rec, 1, &total, &gen, mbus::kRecordSize) > 0;
  switch (ev.id) {
    case mbus::kEventDeviceAdded:
      if (!found) {
        lm_log("devicePtr is null");
        return;
      }
      lm_log("Receive Event : SCE_MBUS_EVENT_DEVICE_ADDED%s [DeviceId:0x%llx][type:%d][subType:%d]",
          generated ? " (Generated by LoginMgr)" : "", static_cast<unsigned long long>(ev.device_id), ev.type,
          ev.sub_type);
      on_device_added(rec, generated);
      host::note_unimplemented("eboot LoginMgr 0x1FDFC0 after onDeviceAdded not reproduced");
      return;
    case mbus::kEventOwnerChanged:
      lm_log("Receive Event : SCE_MBUS_EVENT_DEVICE_OWNER_CHANGED [DeviceId:0x%llx][UserId:0x%08x]",
          static_cast<unsigned long long>(ev.device_id), static_cast<uint32_t>(ev.user_id));
      host::note_unimplemented("eboot LoginMgr onDeviceOwnerChanged (0x1D1F10) not reproduced");
      return;
    default:
      host::note_unimplemented("eboot LoginMgr watch thread mbus event " + std::to_string(ev.id) + " not reproduced");
      return;
  }
}

// GetUnassignedDeviceInfo (0x214B50, a2 = a3 = 0): every device whose owner is -1 or 0
// (types 5 / 10-on-bus-2 aside) and that is not marked (+224 bit 4) is reported as added,
// "Generated by LoginMgr" (CanConnectViaUsb 0x1FDA90 / bus-transition entry 0x1FDD60 find
// nothing on the host).
void scan_unassigned() {
  uint8_t cond[256];
  mbus::init_condition(cond, sizeof cond);
  for (int i = 0; i < 11; ++i) std::memset(cond + 24 + 16 * i, 0xFF, 4);
  uint8_t recs[16][mbus::kRecordSize];
  int32_t total = 0, gen = 0;
  const int32_t n = mbus::get_device_info_by_condition(cond, 0, &recs[0][0], 16, &total, &gen, mbus::kRecordSize);
  for (int32_t i = 0; i < n; ++i) {
    const uint8_t* r = recs[i];
    if (r[17] == 1 && rd<int32_t>(r, 12) != 15) continue;  // GetDeviceList (0x20C4A0)
    const int32_t owner = rd<int32_t>(r, 200), type = rd<int32_t>(r, 12);
    if (static_cast<uint32_t>(owner + 1) >= 2 && type != 5 && !(type == 10 && rd<int32_t>(r, 8) == 2)) continue;
    if (rd<uint32_t>(r, 224) & 0x10) continue;
    mbus::Event ev;
    ev.id = mbus::kEventDeviceAdded;
    ev.device_id = rd<uint64_t>(r, 0);
    ev.type = type;
    handle_event(ev, true);
  }
}

// "SceLoginMgrWatchThr" (watch_thread.cpp Run, 0x215460).
void watch_thread() {
  const int32_t handle = mbus::create_event_handle();
  // System state (ze0ky5Q1yE8) 1000: not standby; first pass over the unassigned devices
  // (0x214AA0 -> 0x214B50(0, 0)), then WATCH_THREAD_READY.
  scan_unassigned();
  set_flag(kEvWatchThreadReady);
  for (;;) {
    mbus::Event ev;
    if (mbus::receive_event(handle, &ev, true) > 0) handle_event(ev, false);  // CheckMbusEvent 0x215A20
  }
}

// RunDisableWaitData (0x1CC670): every request queued while the event watch was off.
void run_disable_wait_data() {
  lm_log("[RunDisableWaitData]");
  for (;;) {
    Record r;
    {
      std::lock_guard<std::mutex> l(mgr().queue_mu);
      if (mgr().wait_data.empty()) break;  // 0x1CC4E0 -> 0x80B60009
      r = mgr().wait_data.front();
      mgr().wait_data.pop_front();
    }
    post_event(r);
  }
}

// startEventWatch (0x1EDBD0).
void start_event_watch(int32_t mode) {
  lm_log("[LoginMgr] startEventWatch() mode:%d", mode);
  bool start;
  {
    std::lock_guard<std::mutex> l(mgr().mode_mu);
    mgr().mode = mode;
    start = !mgr().watch_started;
    mgr().watch_started = true;
  }
  // The Morpheus device (type 12) query that follows finds no VR headset on the host.
  if (start) std::thread(watch_thread).detach();  // +20528 started once (sub_356C20)
}

// "SceLoginMgrEventThr" (event_thread.cpp Run, 0x1C87B0) for the bits the host raises.
void event_thread() {
  for (;;) {
    uint64_t bits;
    {
      std::unique_lock<std::mutex> l(mgr().flag_mu);
      mgr().flag_cv.wait(l, [] { return mgr().flag != 0; });
      bits = mgr().flag;  // wait mode 34: OR + clear
      mgr().flag = 0;
    }
    if (bits & kEvStartEventWatch) {
      lm_log("Event Received : SCE_LOGIN_MGR_EVENT_START_EVENT_WATCH");
      start_event_watch(1);
      // SetInitializeFinishedFlag (0x1C94B0): SceBootStatusFlags |= SCE_BOOT_STAT_LOGIN_MGR.
      if (kernel::EventFlag* ef = kernel::open_event_flag("SceBootStatusFlags")) {
        kernel::set_event_flag(ef, 0x100);
        lm_log("Set event flag [SCE_BOOT_STAT_LOGIN_MGR]");
      }
      // SetLoginMgrStateFlag (0x1C95D0) opens "SceLoginMgrStateFlag", which SceShellCore
      // creates; the host has no such flag, so the open fails and the step is skipped as
      // the eboot does on that error.
      if (kernel::EventFlag* ef = kernel::open_event_flag("SceLoginMgrStateFlag")) kernel::set_event_flag(ef, 1);
      else host::note_unimplemented("SceLoginMgrStateFlag (SceShellCore LoginMgr server) not created on the host; 0x1C95D0 open fails");
    }
    if (bits & kEvWatchThreadReady) {
      lm_log("Event Received : SCE_LOGIN_MGR_EVENT_WATCH_THREAD_READY");
      if (kSystemStateWorking == 1000 && current_mode() == 1) {
        {
          std::lock_guard<std::mutex> l(mgr().queue_mu);
          mgr().watch_enabled = true;  // +368
        }
        run_disable_wait_data();
      }
    }
    if (bits & ~(kEvStartEventWatch | kEvWatchThreadReady))
      host::note_unimplemented("eboot LoginMgr event thread bits other than START_EVENT_WATCH / WATCH_THREAD_READY not reproduced");
  }
}

// _StartEventWatch (0x1C7430): sceKernelSetEventFlag(SceLoginMgrEventFlag, 0x20). The event
// thread is created by LoginMgr::initialize (0x1ECC00, "SceLoginMgrEventThr"); the host
// creates it on first use.
void StartEventWatch() {
  {
    std::lock_guard<std::mutex> l(mgr().flag_mu);
    if (!mgr().event_thread) {
      mgr().event_thread = true;
      std::thread(event_thread).detach();
    }
  }
  set_flag(kEvStartEventWatch);
}
SSN_ICALL("Sce.Vsh.ShellUI.LoginMgrProxy.NativeCall::_StartEventWatch", StartEventWatch);

