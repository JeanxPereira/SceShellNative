// The eboot's native LoginMgr device path (FW 4.03): how a controller that is added to
// the bus reaches ShellUI's managed LoginMgr as a login request.
//
//   _StartEventWatch (icall 0x1C7430)          sets bit 0x20 of "SceLoginMgrEventFlag"
//   event thread (event_thread.cpp, 0x1C87B0)  START_EVENT_WATCH: mode 1 (0x1EDBD0), the
//                                              watch thread is started once, SceBootStatusFlags
//                                              |= SCE_BOOT_STAT_LOGIN_MGR (0x1C94B0)
//   watch thread (watch_thread.cpp, 0x215460)  first pass: every unassigned device is
//                                              "added" (Generated by LoginMgr, 0x214AA0 ->
//                                              0x214B50); then WATCH_THREAD_READY (0x800);
//                                              then each sceMbus event (0x215A20 -> 0x215D90)
//   event thread, WATCH_THREAD_READY           system state 1000 and mode 1: event watch on
//                                              (+368), queued requests posted (0x1CC670)
//   device_manager.cpp onDeviceAdded 0x1CFD40  an unassigned controller that is not
//                                              auto-assigned is queued (DeviceQueueMgr
//                                              Enqueue 0x1CC040)
//   PostEvent 0x1C9A30                         {"entry":"login","deviceId":...} becomes
//                                              "psaccounts:login?deviceId=..." and goes to
//                                              the managed LaunchByUriAsync delegate (0x1F0950)
//
// The managed handler (LoginMgr Utility.OnLaunchByUriAsync) boots the URI, which opens the
// "who is using this controller" login screen for that device; logging in there binds the
// device to the user (_Login, login_mgr_login.cpp).
//
// Reproduced for the device classes the host bus can hold (the USB DualSense of
// libSceMbus). Steps that act on hardware or state the host does not have are cited and
// reported once through host::note_unimplemented.
#include <condition_variable>
