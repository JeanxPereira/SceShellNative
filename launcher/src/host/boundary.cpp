namespace ssn::host {

Boundary& Boundary::get() {
  static Boundary instance;
  return instance;
}

std::string Boundary::table() const {
  std::string t = "# host boundary table (generated by the launcher)\n";
  for (const auto& i : icalls_) t += std::string("icall ") + i.name + "\n";
  for (const auto& p : pinvokes_) t += std::string("pinvoke ") + p.lib + "!" + p.entry + "=" + p.symbol + "\n";
  for (const auto& l : libraries_) t += "library " + l.lib + "=" + l.path + "\n";
  for (const auto& p : policies_) t += "policy " + p + "\n";
  return t;
}

void Boundary::install_into_mono() const {
  for (const auto& i : icalls_) mono_add_internal_call(i.name, i.fn);
  for (const auto& l : libraries_) mono_dllmap_insert(nullptr, l.lib.c_str(), nullptr, l.path.c_str(), nullptr);
  log::info("boundary", "{} icalls, {} pinvokes, {} passthrough libraries served by the host", icalls_.size(), pinvokes_.size(),
            libraries_.size());
}

namespace {
std::mutex g_mutex;
std::map<std::string, int> g_hits;
int g_order = 0;
}  // namespace

void note_unimplemented(const std::string& id) {
  {
    std::lock_guard lock(g_mutex);
    auto [it, inserted] = g_hits.try_emplace(id, 0);
    ++it->second;
    // Diagnostics: SSN_TRACE_STUBS=1 logs the first 40 hits of each entry, not only the first.
    static const bool trace_all = [] {
      const char* v = std::getenv("SSN_TRACE_STUBS");
      return v && *v == '1';
    }();
    if (!inserted) {
      if (trace_all && it->second <= 40) log::info("stub-hit", "{}", id);
      // with tracing, the running count at every power of two (call-frequency ranking)
      if (trace_all && it->second >= 64 && (it->second & (it->second - 1)) == 0)
        log::info("stub-count", "{}	{}", it->second, id);
      return;
    }
    ++g_order;
  }
  log::warn("stub", "#{} {}", g_order, id);
}

void dump_unimplemented_counts() {
  std::lock_guard lock(g_mutex);
  for (const auto& [id, n] : g_hits) log::info("stub-count", "{}\t{}", n, id);
}

}  // namespace ssn::host
